def recuperar_chunks(pergunta, top_k=6):
    """Recupera os top-k chunks mais relevantes para a pergunta."""
    embedding_pergunta = modelo_embedding.encode([pergunta]).tolist()
    resultados = colecao.query(
        query_embeddings=embedding_pergunta,
        n_results=top_k,
        include=['documents', 'metadatas', 'distances']
    )
    chunks_recuperados = []
    for i in range(len(resultados['documents'][0])):
        chunks_recuperados.append({
            'texto': resultados['documents'][0][i],
            'artigo': resultados['metadatas'][0][i]['artigo'],
            'capitulo': resultados['metadatas'][0][i]['capitulo'],
            'distancia': resultados['distances'][0][i]
        })
    return chunks_recuperados

