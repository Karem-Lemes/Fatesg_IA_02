import requests

def gerar_resposta_maritaca(pergunta, chunks_contexto):
    """Gera resposta usando a API da Maritaca com os chunks reranqueados como contexto."""

    contexto = '\n\n'.join([
        f"[{c['artigo']} — {c['capitulo']}]\n{c['texto']}"
        for c in chunks_contexto
    ])

    prompt = f"""Você é um assistente jurídico especializado na Resolução CNJ nº 615/2025,
que estabelece diretrizes para uso de Inteligência Artificial no Poder Judiciário brasileiro.

Use APENAS o contexto abaixo para responder. Se a resposta não estiver no contexto, diga que
não encontrou a informação.

CONTEXTO:
{contexto}

PERGUNTA: {pergunta}

RESPOSTA:"""

    headers = {
        'Authorization': f'Key {MARITACA_API_KEY}',
        'Content-Type': 'application/json'
    }

    payload = {
        'model': 'sabia-3',
        'messages': [{'role': 'user', 'content': prompt}],
        'max_tokens': 500,
        'temperature': 0.3
    }

    response = requests.post(
        'https://chat.maritaca.ai/api/chat/completions',
        headers=headers,
        json=payload
    )

    if response.status_code == 200:
        return response.json()['choices'][0]['message']['content']
    else:
        return f'Erro na API: {response.status_code} — {response.text}'

