def rag_avancado(pergunta, top_k=10, top_n=3):
    """
    Pipeline RAG Avançado completo:
    1. Recuperação Top-K no ChromaDB
    2. Re-ranqueamento por similaridade de cosseno
    3. Geração com Maritaca sabia-3
    """
    print(f'❓ Pergunta: {pergunta}')
    print('─' * 60)

    # Etapa 1: Recuperação
    chunks_recuperados = recuperar_chunks(pergunta, top_k=top_k)
    print(f'📦 {len(chunks_recuperados)} chunks recuperados (Top-{top_k})')

    # Etapa 2: Re-ranqueamento
    chunks_finais = reranquear(pergunta, chunks_recuperados, top_n=top_n)
    print(f'🔄 Re-ranqueamento aplicado → Top-{top_n} selecionados')
    print('\n📌 Chunks usados como contexto:')
    for i, c in enumerate(chunks_finais):
        print(f'  [{i+1}] Score: {c["score_reranking"]:.4f} | {c["artigo"]}')

    # Etapa 3: Geração
    print('\n💬 Resposta gerada pelo sabia-3:')
    print('─' * 60)
    resposta = gerar_resposta_maritaca(pergunta, chunks_finais)
    print(resposta)
    print('─' * 60)
    return resposta

