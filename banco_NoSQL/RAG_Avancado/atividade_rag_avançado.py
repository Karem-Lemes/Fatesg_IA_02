import numpy as np

def similaridade_cosseno(vec1, vec2):
    """Calcula a similaridade de cosseno entre dois vetores."""
    vec1, vec2 = np.array(vec1), np.array(vec2)
    return np.dot(vec1, vec2) / (np.linalg.norm(vec1) * np.linalg.norm(vec2))

def reranquear(pergunta, chunks, top_n=3):
    """Reordena os chunks por similaridade de cosseno e retorna os top-n."""
    embedding_pergunta = modelo_embedding.encode([pergunta])[0]

    for chunk in chunks:
        embedding_chunk = modelo_embedding.encode([chunk['texto']])[0]
        chunk['score_reranking'] = similaridade_cosseno(embedding_pergunta, embedding_chunk)

    chunks_reranqueados = sorted(chunks, key=lambda x: x['score_reranking'], reverse=True)
    return chunks_reranqueados[:top_n]

